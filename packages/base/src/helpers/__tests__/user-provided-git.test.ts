import {
  CI_JOB_NAME,
  CI_JOB_URL,
  CI_PIPELINE_ID,
  CI_PIPELINE_NAME,
  CI_PIPELINE_NUMBER,
  CI_PIPELINE_URL,
  CI_PROVIDER_NAME,
  CI_STAGE_NAME,
  CI_WORKSPACE_PATH,
  GIT_BRANCH,
  GIT_COMMIT_AUTHOR_DATE,
  GIT_COMMIT_AUTHOR_EMAIL,
  GIT_COMMIT_AUTHOR_NAME,
  GIT_COMMIT_COMMITTER_DATE,
  GIT_COMMIT_COMMITTER_EMAIL,
  GIT_COMMIT_COMMITTER_NAME,
  GIT_COMMIT_MESSAGE,
  GIT_PULL_REQUEST_BASE_BRANCH,
  GIT_PULL_REQUEST_BASE_BRANCH_SHA,
  GIT_REPOSITORY_URL,
  GIT_SHA,
  GIT_TAG,
  GIT_HEAD_SHA,
  CI_JOB_ID,
} from '../tags'
import {getUserCISpanTags, getUserGitSpanTags} from '../user-provided-git'

describe('getUserGitSpanTags', () => {
  const OO_GIT_METADATA = {
    OO_GIT_BRANCH: 'OO_GIT_BRANCH',
    OO_GIT_COMMIT_AUTHOR_DATE: 'OO_GIT_COMMIT_AUTHOR_DATE',
    OO_GIT_COMMIT_AUTHOR_EMAIL: 'OO_GIT_COMMIT_AUTHOR_EMAIL',
    OO_GIT_COMMIT_AUTHOR_NAME: 'OO_GIT_COMMIT_AUTHOR_NAME',
    OO_GIT_COMMIT_COMMITTER_DATE: 'OO_GIT_COMMIT_COMMITTER_DATE',
    OO_GIT_COMMIT_COMMITTER_EMAIL: 'OO_GIT_COMMIT_COMMITTER_EMAIL',
    OO_GIT_COMMIT_COMMITTER_NAME: 'OO_GIT_COMMIT_COMMITTER_NAME',
    OO_GIT_COMMIT_MESSAGE: 'OO_GIT_COMMIT_MESSAGE',
    OO_GIT_COMMIT_SHA: 'OO_GIT_COMMIT_SHA',
    OO_GIT_REPOSITORY_URL: 'OO_GIT_REPOSITORY_URL',
    OO_GIT_PULL_REQUEST_BASE_BRANCH: 'OO_GIT_PULL_REQUEST_BASE_BRANCH',
    OO_GIT_PULL_REQUEST_BASE_BRANCH_SHA: 'OO_GIT_PULL_REQUEST_BASE_BRANCH_SHA',
    OO_GIT_COMMIT_HEAD_SHA: 'OO_GIT_COMMIT_HEAD_SHA',
  }

  it('reads user defined git metadata successfully', () => {
    process.env = {...OO_GIT_METADATA}
    const result = getUserGitSpanTags()
    expect(result).toEqual({
      [GIT_REPOSITORY_URL]: 'OO_GIT_REPOSITORY_URL',
      [GIT_BRANCH]: 'OO_GIT_BRANCH',
      [GIT_SHA]: 'OO_GIT_COMMIT_SHA',
      [GIT_COMMIT_MESSAGE]: 'OO_GIT_COMMIT_MESSAGE',
      [GIT_COMMIT_COMMITTER_DATE]: 'OO_GIT_COMMIT_COMMITTER_DATE',
      [GIT_COMMIT_COMMITTER_EMAIL]: 'OO_GIT_COMMIT_COMMITTER_EMAIL',
      [GIT_COMMIT_COMMITTER_NAME]: 'OO_GIT_COMMIT_COMMITTER_NAME',
      [GIT_COMMIT_AUTHOR_DATE]: 'OO_GIT_COMMIT_AUTHOR_DATE',
      [GIT_COMMIT_AUTHOR_EMAIL]: 'OO_GIT_COMMIT_AUTHOR_EMAIL',
      [GIT_COMMIT_AUTHOR_NAME]: 'OO_GIT_COMMIT_AUTHOR_NAME',
      [GIT_PULL_REQUEST_BASE_BRANCH]: 'OO_GIT_PULL_REQUEST_BASE_BRANCH',
      [GIT_PULL_REQUEST_BASE_BRANCH_SHA]: 'OO_GIT_PULL_REQUEST_BASE_BRANCH_SHA',
      [GIT_HEAD_SHA]: 'OO_GIT_COMMIT_HEAD_SHA',
    })
  })

  it('does not include empty values', () => {
    process.env = {
      ...OO_GIT_METADATA,
      OO_GIT_COMMIT_SHA: undefined,
      OO_GIT_PULL_REQUEST_BASE_BRANCH: undefined,
      OO_GIT_PULL_REQUEST_BASE_BRANCH_SHA: undefined,
      OO_GIT_COMMIT_HEAD_SHA: undefined,
    }
    const result = getUserGitSpanTags()
    expect(result).toEqual({
      [GIT_REPOSITORY_URL]: 'OO_GIT_REPOSITORY_URL',
      [GIT_BRANCH]: 'OO_GIT_BRANCH',
      [GIT_COMMIT_MESSAGE]: 'OO_GIT_COMMIT_MESSAGE',
      [GIT_COMMIT_COMMITTER_DATE]: 'OO_GIT_COMMIT_COMMITTER_DATE',
      [GIT_COMMIT_COMMITTER_EMAIL]: 'OO_GIT_COMMIT_COMMITTER_EMAIL',
      [GIT_COMMIT_COMMITTER_NAME]: 'OO_GIT_COMMIT_COMMITTER_NAME',
      [GIT_COMMIT_AUTHOR_DATE]: 'OO_GIT_COMMIT_AUTHOR_DATE',
      [GIT_COMMIT_AUTHOR_EMAIL]: 'OO_GIT_COMMIT_AUTHOR_EMAIL',
      [GIT_COMMIT_AUTHOR_NAME]: 'OO_GIT_COMMIT_AUTHOR_NAME',
    })
  })

  it('has both branch and tag when available', () => {
    process.env = {...OO_GIT_METADATA, OO_GIT_TAG: 'OO_GIT_TAG'}
    const result = getUserGitSpanTags()
    expect(result).toEqual({
      [GIT_TAG]: 'OO_GIT_TAG',
      [GIT_BRANCH]: 'OO_GIT_BRANCH',
      [GIT_REPOSITORY_URL]: 'OO_GIT_REPOSITORY_URL',
      [GIT_SHA]: 'OO_GIT_COMMIT_SHA',
      [GIT_COMMIT_MESSAGE]: 'OO_GIT_COMMIT_MESSAGE',
      [GIT_COMMIT_COMMITTER_DATE]: 'OO_GIT_COMMIT_COMMITTER_DATE',
      [GIT_COMMIT_COMMITTER_EMAIL]: 'OO_GIT_COMMIT_COMMITTER_EMAIL',
      [GIT_COMMIT_COMMITTER_NAME]: 'OO_GIT_COMMIT_COMMITTER_NAME',
      [GIT_COMMIT_AUTHOR_DATE]: 'OO_GIT_COMMIT_AUTHOR_DATE',
      [GIT_COMMIT_AUTHOR_EMAIL]: 'OO_GIT_COMMIT_AUTHOR_EMAIL',
      [GIT_COMMIT_AUTHOR_NAME]: 'OO_GIT_COMMIT_AUTHOR_NAME',
      [GIT_PULL_REQUEST_BASE_BRANCH]: 'OO_GIT_PULL_REQUEST_BASE_BRANCH',
      [GIT_PULL_REQUEST_BASE_BRANCH_SHA]: 'OO_GIT_PULL_REQUEST_BASE_BRANCH_SHA',
      [GIT_HEAD_SHA]: 'OO_GIT_COMMIT_HEAD_SHA',
    })
  })

  it('returns an empty object if no user git is defined', () => {
    process.env = {}
    const result = getUserGitSpanTags()
    expect(result).toEqual({})
  })
})

